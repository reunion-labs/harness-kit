  assert.equal(readFileSync(join(repo, "AGENTS.md"), "utf8"), "# Important existing rules\n");

  captureLegacyEntries(repo);
  assert.throws(() => syncCmd(repo, { adoptExisting: true }), /candidate|receipt/i);
