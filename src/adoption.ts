function documentLike(path: string): boolean {
  return AGENT_ENTRY_NAMES.has(basename(path)) || DOCUMENT_EXTENSIONS.has(extname(path).toLowerCase());
}

function cleanReference(raw: string): string | null {
  let value = raw.trim();
  if (value.startsWith("<") && value.endsWith(">")) value = value.slice(1, -1).trim();
  else value = value.split(/\s+/)[0] ?? "";
  if (!value || value.startsWith("#") || value.startsWith("//") || /^[a-z][a-z0-9+.-]*:/i.test(value)) return null;
  value = value.replace(/[?#].*$/, "");
  try {
    value = decodeURIComponent(value);
  } catch {
    return null;
  }
  return value || null;
}

// A path is ASCII; anything else around it (CJK text or punctuation such as
// 、，。（）, Markdown emphasis, quotes) is a boundary. A sentence-ending
// period after a path is a boundary too, unless it continues the name.
const NOT_PATH_BEFORE = String.raw`(?:^|[^A-Za-z0-9._%/@\\-])`;
const NOT_PATH_AFTER = String.raw`(?=$|[^A-Za-z0-9._%/\\-]|\.(?![A-Za-z0-9_%/\\-]))`;
const IMPORT_REFERENCE = new RegExp(String.raw`${NOT_PATH_BEFORE}@([A-Za-z0-9._/\\%-]+)`, "gm");
const MENTION_REFERENCE = new RegExp(
  String.raw`${NOT_PATH_BEFORE}((?:(?:\.{1,2})\/)*[A-Za-z0-9._%-]+(?:\/[A-Za-z0-9._%-]+)*\.(?:md|mdx|markdown|txt|rst|adoc|asciidoc|org))${NOT_PATH_AFTER}`,
  "gim",
);

/**
 * A scheme-less URL such as `api-sg-edge.example.org` or
 * `docs.example.com/guide.md`: its first segment is a host name with at least
 * three labels. `.org` is also an Org-mode extension, so only an unresolved
 * mention is dropped this way; a real file of that name still resolves.
 */
function looksLikeHostName(reference: string): boolean {
  const first = reference.replace(/^\/+/, "").split("/")[0] ?? "";
  return /^(?:[a-z0-9](?:[a-z0-9-]*[a-z0-9])?\.){2,}[a-z]{2,}$/i.test(first);
}

/**
 * Document references by how they were written. Markdown links and `@path`
 * imports are deliberate and resolve strictly; a bare path is only a mention
 * (prose shorthand, a directory-tree sketch, an external knowledge-base path).
 */
function explicitReferences(content: string): Map<string, GuidanceReferenceKind> {
  const references = new Map<string, GuidanceReferenceKind>();
  const add = (path: string, kind: GuidanceReferenceKind): void => {
    // A path that is also linked or imported anywhere keeps the strict kind.
    if (references.get(path) === undefined || references.get(path) === "mention") references.set(path, kind);
  };
  for (const match of content.matchAll(/\[[^\]]*\]\(([^)]+)\)/g)) {
    if ((match.index ?? 0) > 0 && content[(match.index ?? 0) - 1] === "!") continue;
    const path = cleanReference(match[1] ?? "");
    if (path && documentLike(path)) add(path, "link");
  }
  const prose = content.replace(/!?\[[^\]]*\]\([^)]+\)/g, "");
  for (const match of prose.matchAll(IMPORT_REFERENCE)) {
    const path = cleanReference(match[1] ?? "");
    if (path && documentLike(path)) add(path, "import");
  }
  for (const match of prose.matchAll(MENTION_REFERENCE)) {
    const path = cleanReference(match[1] ?? "");
    if (path) add(path, "mention");
  }
  return references;
}

type ResolvedGuidanceReference =
  | { status: "resolved"; path: string }
  | { status: "missing" | "outside-repository" | "unsafe" };

/**
 * Directories a reference may be relative to. The source directory and the
 * repository root come first, so earlier resolutions never change. Mentions
 * then fall back to intermediate ancestors, nearest first: Skill and package
 * documents usually write paths relative to their own root.
 */
function referenceBases(sourcePath: string, kind: GuidanceReferenceKind): string[] {
  const sourceDirectory = dirname(sourcePath);
  const bases = [sourceDirectory, "."];
  if (kind !== "mention") return bases;
  for (let cursor = dirname(sourceDirectory); cursor !== "." && cursor !== sep; cursor = dirname(cursor)) bases.push(cursor);
  return bases;
}

function resolveGuidanceReference(
  repoRoot: string,
  sourcePath: string,
  reference: string,
  kind: GuidanceReferenceKind,
  testHooks: AdoptionCandidateTestHooks,
): ResolvedGuidanceReference {
  const candidates = reference.startsWith("/")
    ? [resolve(repoRoot, reference.slice(1))]
    : referenceBases(sourcePath, kind).map((base) => resolve(repoRoot, base, reference));
  // An existing but unreadable candidate is never downgraded to "missing".
  let unsafe = false;
  let outside = 0;
  for (const absolute of candidates) {
    if (!inside(repoRoot, absolute)) {
      outside++;
      continue;
    }
    if (!entryExists(absolute)) continue;
    let stat;
    try {
      const path = relative(repoRoot, absolute);
      if (!safeEvidencePath(path) || !ensureNoSymlinkDirectoryChain(repoRoot, dirname(absolute), `guidance ${path}`, false)) {
        unsafe = true;
        continue;
      }
      stat = lstatSync(absolute);
      if (!stat.isSymbolicLink() && !stat.isFile()) {
        unsafe = true;
        continue;
      }
      if (stat.isFile()) {
        const source = readOptionalRepositoryFile(
          repoRoot,
          path,
          `guidance ${path}`,
          testHooks.afterGuidanceFileLstat,
        );
        if (!source || !textCanContainReferences(source.bytes)) {
          unsafe = true;
          continue;
        }
      }
    } catch {
      unsafe = true;
      continue;
    }
    const path = relative(repoRoot, absolute);
    if (safeEvidencePath(path)) return { status: "resolved", path };
    unsafe = true;
  }
  if (unsafe) return { status: "unsafe" };
  return { status: outside === candidates.length ? "outside-repository" : "missing" };
}

function resolveGuidanceSymlinkTarget(
  repoRoot: string,
  sourcePath: string,
  linkTarget: string,
  testHooks: AdoptionCandidateTestHooks,
): string | null {
  const absolute = isAbsolute(linkTarget) ? resolve(linkTarget) : resolve(repoRoot, dirname(sourcePath), linkTarget);
  if (!inside(repoRoot, absolute) || !entryExists(absolute)) return null;
  try {
    const path = relative(repoRoot, absolute);
    if (!safeEvidencePath(path) || !ensureNoSymlinkDirectoryChain(repoRoot, dirname(absolute), `guidance ${path}`, false))
      return null;
    const stat = lstatSync(absolute);
    if (!stat.isSymbolicLink() && !stat.isFile()) return null;
    if (stat.isFile()) {
      const source = readOptionalRepositoryFile(
        repoRoot,
        path,
        `guidance ${path}`,
        testHooks.afterGuidanceFileLstat,
      );
      if (!source || !textCanContainReferences(source.bytes)) return null;
    }
  } catch {
    return null;
  }
  const path = relative(repoRoot, absolute);
  return safeEvidencePath(path) ? path : null;
}

function liveGuidanceEvidence(
  repoRoot: string,
  path: string,
  testHooks: AdoptionCandidateTestHooks,
): LiveGuidanceEvidence {
  const absolute = join(repoRoot, path);
  if (!ensureNoSymlinkDirectoryChain(repoRoot, dirname(absolute), `guidance ${path}`, false))
    throw new Error(`guidance disappeared while it was being inspected: ${path}`);
  const stat = lstatSync(absolute);
  const mode = permissionMode(stat.mode);
  if (stat.isSymbolicLink()) {
    const linkTarget = readlinkSync(absolute);
    if (!resolveGuidanceSymlinkTarget(repoRoot, path, linkTarget, testHooks))
      throw new Error(`guidance symlink cannot be resolved to a safe in-repo text file: ${path}`);
    return { path, type: "symlink", mode, linkTarget };
  }
  if (!stat.isFile()) throw new Error(`guidance must be a regular file or symlink: ${path}`);
  const source = readOptionalRepositoryFile(
    repoRoot,
    path,
    `guidance ${path}`,
    testHooks.afterGuidanceFileLstat,
  );
  if (!source) throw new Error(`guidance disappeared while it was being inspected: ${path}`);
  if (!textCanContainReferences(source.bytes)) throw new Error(`guidance must be plain text: ${path}`);
  return { path, type: "file", mode: source.mode, bytes: source.bytes };
}

interface LiveGuidance {
  evidence: LiveGuidanceEvidence[];
  unresolved: AdoptionCandidateUnresolvedReference[];
}

/** Agent guidance that already exists: legacy (non-generated) entries and other clients' rule files. */
function liveGuidanceRoots(root: string, testHooks: AdoptionCandidateTestHooks): Set<string> {
  const found = findGuidanceRootPaths(root);
  const roots = new Set<string>();
  for (const path of found.entries) {
    if (!AGENT_ENTRY_NAMES.has(basename(path)) || !safeEvidencePath(path)) continue;
    const absolute = join(root, path);
    if (entryExists(absolute) && isLegacyEntry(root, path, testHooks)) roots.add(path);
  }
  for (const path of MANAGED_ENTRY_PATHS) {
    if (!AGENT_ENTRY_NAMES.has(basename(path))) continue;
    const absolute = join(root, path);
    if (entryExists(absolute) && isLegacyEntry(root, path, testHooks)) roots.add(path);
  }
  for (const path of found.clientRules) {
    if (safeEvidencePath(path) && entryExists(join(root, path)) && isLegacyEntry(root, path, testHooks)) roots.add(path);
  }
  return roots;
}

function discoverGuidance(repo: string, testHooks: AdoptionCandidateTestHooks = {}): LiveGuidance {
  const root = repositoryRoot(repo);
  const entryPaths = liveGuidanceRoots(root, testHooks);

  const evidence = new Set([...entryPaths].filter((path) => !MANAGED_ENTRY_PATHS.includes(path)));
  const unresolved: AdoptionCandidateUnresolvedReference[] = [];
  const queue = [...entryPaths];
  const queued = new Set(queue);
  const reviewed = new Set<string>();
  while (queue.length) {
    const sourcePath = queue.shift()!;
    if (reviewed.has(sourcePath)) continue;
    reviewed.add(sourcePath);
    const absolute = join(root, sourcePath);
    if (!ensureNoSymlinkDirectoryChain(root, dirname(absolute), `guidance ${sourcePath}`, false))
      throw new Error(`guidance disappeared while it was being inspected: ${sourcePath}`);
    const stat = lstatSync(absolute);
    if (stat.isSymbolicLink()) {
      const target = resolveGuidanceSymlinkTarget(root, sourcePath, readlinkSync(absolute), testHooks);
      if (!target) throw new Error(`guidance symlink cannot be resolved to a safe in-repo text file: ${sourcePath}`);
      if (!MANAGED_ENTRY_PATHS.includes(target)) evidence.add(target);
      if (!reviewed.has(target) && !queued.has(target)) {
        queue.push(target);
        queued.add(target);
      }
      continue;
    }
    if (!stat.isFile()) continue;
    const source = readOptionalRepositoryFile(
      root,
      sourcePath,
      `guidance ${sourcePath}`,
      testHooks.afterGuidanceFileLstat,
    );
    if (!source || !textCanContainReferences(source.bytes)) continue;
    for (const [reference, kind] of explicitReferences(source.bytes.toString("utf8"))) {
      const resolved = resolveGuidanceReference(root, sourcePath, reference, kind, testHooks);
      if (resolved.status !== "resolved") {
        // Only a mention naming no in-repository file is recorded instead of
        // failing; unsafe targets and strict links/imports still fail closed.
        if (kind !== "mention" || resolved.status === "unsafe")
          throw new Error(`cannot safely resolve referenced guidance ${reference} from ${sourcePath}${resolved.status === "outside-repository" ? " (outside the repository)" : ""}`);
        if (!looksLikeHostName(reference)) unresolved.push({ source: sourcePath, reference, kind, reason: resolved.status });
        continue;
      }
      const target = resolved.path;
      if (!MANAGED_ENTRY_PATHS.includes(target)) evidence.add(target);
      if (!reviewed.has(target) && !queued.has(target)) {
        queue.push(target);
        queued.add(target);
      }
    }
  }
  return {
    evidence: [...evidence].sort().map((path) => liveGuidanceEvidence(root, path, testHooks)),
    unresolved: unresolved.sort(compareUnresolved),
  };
}

function compareUnresolved(left: AdoptionCandidateUnresolvedReference, right: AdoptionCandidateUnresolvedReference): number {
  const order = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);
  return order(left.source, right.source) || order(left.reference, right.reference);
}

function posixPath(path: string): string {
  return path.split(sep).join("/");
}

/** File or symlink evidence for one landing path, read without following links. */
function liveLandingEvidence(repoRoot: string, path: string): LiveGuidanceEvidence {
  const absolute = join(repoRoot, path);
  if (!ensureNoSymlinkDirectoryChain(repoRoot, dirname(absolute), `landing ${path}`, false))
    throw new Error(`landing disappeared while it was being inspected: ${path}`);
  const stat = lstatSync(absolute);
  if (stat.isSymbolicLink()) return { path, type: "symlink", mode: permissionMode(stat.mode), linkTarget: readlinkSync(absolute) };
  const source = readOptionalRepositoryFile(repoRoot, path, `landing ${path}`);
  if (!source) throw new Error(`landing disappeared while it was being inspected: ${path}`);
  return { path, type: "file", mode: source.mode, bytes: source.bytes };
}

/**
 * Where migrated rules landed: Harness-owned files under .agents/ plus every
 * root=repo knowledge document registered in place. Symlinks are recorded,
 * never followed; any other special file fails closed.
 */
function discoverLanding(repoRoot: string, manifest: Manifest): LiveGuidanceEvidence[] {
  const paths = new Set<string>();
  const walk = (relativePath: string): void => {
    const absolute = join(repoRoot, relativePath);
    if (!entryExists(absolute)) return;
    const stat = lstatSync(absolute);
    const key = posixPath(relativePath);
    if (stat.isSymbolicLink() || stat.isFile()) {
      if (!LANDING_EXCLUDED_FILES.has(key)) paths.add(relativePath);
      return;
    }
    if (!stat.isDirectory()) throw new Error(`landing must be a regular file, symlink, or directory: ${key}`);
    if (LANDING_EXCLUDED_DIRECTORIES.has(key) || ALWAYS_PRUNED_DIRECTORY_NAMES.has(basename(relativePath))) return;
    if (!inside(repoRoot, realpathSync(absolute))) throw new Error(`landing directory resolves outside the repository: ${key}`);
    for (const name of readdirSync(absolute).sort()) walk(join(relativePath, name));
  };
  walk(LANDING_ROOT);
  for (const knowledge of manifest.knowledge ?? []) {
    if (knowledge.root !== "repo" || typeof knowledge.path !== "string") continue;
    const relativePath = safeRelativePath(knowledge.path.replace(/\/+$/, ""), "repo knowledge");
    if (!ensureNoSymlinkDirectoryChain(repoRoot, dirname(join(repoRoot, relativePath)), `landing ${relativePath}`, false)) continue;
    walk(relativePath);
  }
  return [...paths].sort().map((path) => liveLandingEvidence(repoRoot, path));
}

function landingEvidenceArtifact(evidence: LiveGuidanceEvidence): string {
  return evidence.type === "file"
    ? join("landing", evidence.path)
    : join("landing-links", `${sha256(evidence.path)}.symlink.json`);
}

interface LiveWorktreeEvidence {
  path: string;
  status: "present" | "deleted";
  evidence?: LiveGuidanceEvidence;
}

/**
 * The onboarding diff outside .agents/ that no other evidence carries. Nothing
 * to compare against without a HEAD commit, and nothing at all outside Git.
 */
function discoverWorktreeChanges(repoRoot: string, covered: ReadonlySet<string>): LiveWorktreeEvidence[] {
  let changes;
  try {
    changes = collectChanges(repoRoot, "HEAD", { mode: "exact" });
  } catch (error) {
    if (error instanceof GitDiffError && error.kind === "not-a-repo") return [];
    throw error;
  }
  if (!changes.resolvedBase) return [];
  const result: LiveWorktreeEvidence[] = [];
  for (const file of changes.files) {
    const path = normalize(file);
    const key = posixPath(path);
    if (key === LANDING_ROOT || key.startsWith(`${LANDING_ROOT}/`) || MANAGED_ENTRY_PATHS.includes(key) || covered.has(key)) continue;
    if (!safeEvidencePath(path)) throw new Error(`worktree change has an unsafe path: ${key}`);
    if (!entryExists(join(repoRoot, path))) {
      result.push({ path, status: "deleted" });
      continue;
    }
    const stat = lstatSync(join(repoRoot, path));
    if (!stat.isSymbolicLink() && !stat.isFile())
      throw new Error(`worktree change must be a regular file or symlink; commit or revert it before preparing: ${key}`);
    result.push({ path, status: "present", evidence: liveLandingEvidence(repoRoot, path) });
  }
  return result.sort((left, right) => (left.path < right.path ? -1 : left.path > right.path ? 1 : 0));
}

function worktreeEvidenceArtifact(evidence: LiveGuidanceEvidence): string {
  return evidence.type === "file"
    ? join("worktree", evidence.path)
    : join("worktree-links", `${sha256(evidence.path)}.symlink.json`);
}

function coveredByOtherEvidence(guidance: readonly LiveGuidanceEvidence[], landing: readonly LiveGuidanceEvidence[]): Set<string> {
  return new Set([...guidance, ...landing].map((item) => posixPath(item.path)));
}

/**
 * A legacy entry Harness already took over: the live file is generated output
 * and the snapshot still holds the audited bytes. Lets a post-takeover re-audit
 * prepare a candidate from the same evidence instead of failing as "stale".
 */
function legacyEntryAdopted(repoRoot: string, entry: AdoptionEntry): boolean {
  try {
    const live = readOptionalRepositoryFile(repoRoot, entry.path, `adopted entry ${entry.path}`);
    if (!live || !isHarnessGenerated(live.bytes.toString("utf8"))) return false;
    if (entry.type === "symlink") return true;
    const snapshot = readOptionalRepositoryFile(repoRoot, entry.snapshot!, `legacy snapshot ${entry.path}`);
    return !!snapshot && snapshot.mode === entry.mode && sha256(snapshot.bytes) === entry.sha256;
  } catch {
    return false;
  }
}

function legacyEvidenceIntact(repoRoot: string, entry: AdoptionEntry): boolean {
  return verifyAdoptionEntry(repoRoot, entry) || legacyEntryAdopted(repoRoot, entry);
}

